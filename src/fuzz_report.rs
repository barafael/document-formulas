//! Fuzz-style cross-check over the `fuzz` example corpus.
//!
//! Parses `examples/fuzz/src/lib.rs`, walks every function's candidate
//! expressions (the same statement shapes [`crate::extract`] lifts), and
//! regenerates `target/fuzz-report.md` with one entry per candidate next to
//! the TeX that `#[formula_doc]` embeds. Functions named `skip_*` must
//! produce no formulas; the human judgment of every entry lives in
//! `examples/fuzz/JUDGEMENT.md`.

use quote::ToTokens;
use syn::{Expr, Item, ItemFn, Pat, Stmt};

use crate::{extract, latex};

const CORPUS: &str = include_str!("../examples/fuzz/src/lib.rs");
const REPORT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/target/fuzz-report.md");

fn collect_fns<'a>(items: &'a [Item], prefix: &str, out: &mut Vec<(String, &'a ItemFn)>) {
    for item in items {
        match item {
            Item::Fn(f) => out.push((prefix.to_string(), f)),
            Item::Mod(m) => {
                let Some((_, inner)) = &m.content else {
                    continue;
                };
                let path = if prefix.is_empty() {
                    m.ident.to_string()
                } else {
                    format!("{prefix}::{}", m.ident)
                };
                collect_fns(inner, &path, out);
            }
            _ => {}
        }
    }
}

/// Candidate statements in extraction order: `(binding name, expression)`,
/// gated by the same formula-shape check [`crate::extract`] applies.
fn candidates(f: &ItemFn) -> Vec<(Option<String>, &Expr)> {
    let mut out = Vec::new();
    for stmt in &f.block.stmts {
        match stmt {
            Stmt::Local(local) => {
                let Some(init) = &local.init else {
                    continue;
                };
                if init.diverge.is_some() {
                    continue;
                }
                let Pat::Ident(binding) = &local.pat else {
                    continue;
                };
                if latex::is_math_like(&init.expr) {
                    out.push((Some(binding.ident.to_string()), init.expr.as_ref()));
                }
            }
            Stmt::Expr(Expr::Return(ret), _) => {
                if let Some(expr) = &ret.expr
                    && latex::is_math_like(expr)
                {
                    out.push((None, expr.as_ref()));
                }
            }
            Stmt::Expr(expr, _) if latex::is_math_like(expr) => {
                out.push((None, expr));
            }
            _ => {}
        }
    }
    out
}

fn render_report(fns: &[(&str, &ItemFn)]) -> String {
    use std::fmt::Write;
    let mut report = String::from(
        "# fuzz report\n\n\
         Auto-generated by `cargo test -p document_formulas fuzz_report`.\n\
         Candidate expressions next to the TeX that `#[formula_doc]` embeds;\n\
         verdicts in `examples/fuzz/JUDGEMENT.md`.\n",
    );
    let mut total = 0usize;
    let mut rendered = 0usize;
    let mut dropped: Vec<String> = Vec::new();
    for (path, f) in fns {
        let name = f.sig.ident.to_string();
        let cands = candidates(f);
        let extracted = extract::extract_formulas(f);
        let expected: Vec<&(Option<String>, &Expr)> = cands
            .iter()
            .filter(|(_, expr)| latex::to_tex(expr).is_some())
            .collect();
        assert_eq!(
            extracted.len(),
            expected.len(),
            "{path}::{name}: extraction and rendering disagree"
        );
        let _ = writeln!(report, "\n## {path}::{name}\n");
        if cands.is_empty() {
            report.push_str("- *(no formulas)*\n");
            if !name.starts_with("skip_") {
                panic!("{path}::{name} yields no formulas but is not named skip_*");
            }
            continue;
        }
        if name.starts_with("skip_") {
            panic!(
                "{path}::{name} yields {} candidates but is named skip_*",
                cands.len()
            );
        }
        for (i, (name_opt, expr)) in cands.iter().enumerate() {
            total += 1;
            let src = expr.to_token_stream().to_string();
            let binding = match name_opt {
                Some(n) => format!("{n} = "),
                None => String::new(),
            };
            let _ = writeln!(report, "- `{binding}{src}`");
            if let Some(tex) = latex::to_tex(expr) {
                rendered += 1;
                let full = match name_opt {
                    Some(n) => format!("{} = {}", latex::ident_tex(n), tex),
                    None => tex,
                };
                assert_eq!(
                    full,
                    latex::formula_tex(&extracted[i]),
                    "{path}::{name}: report disagrees with extraction"
                );
                let _ = writeln!(report, "  → `{full}`");
            } else {
                dropped.push(format!("{path}::{name}"));
                report.push_str("  → *(not extracted: unrenderable)*\n");
            }
        }
    }
    assert_eq!(
        dropped,
        [
            "binders::diverging_init",
            "weird::nonmath_method_arithmetic",
            "weird::turbofish_binding",
        ],
        "exactly these known cases may be formula-shaped yet unrenderable"
    );
    assert!(
        rendered >= 60,
        "expected a stupendous number of rendered formulas, got {rendered}"
    );
    let _ = writeln!(
        report,
        "\n---\n\n{total} formula-shaped candidates: {rendered} rendered and extracted, {} deliberately not extracted (unrenderable)\n",
        dropped.len()
    );
    report
}

#[test]
fn fuzz_report() {
    let file = syn::parse_file(CORPUS).expect("corpus must parse");
    let mut fns = Vec::new();
    collect_fns(&file.items, "", &mut fns);
    assert!(fns.len() >= 80, "expected a stupendous corpus");
    let borrowed: Vec<(&str, &ItemFn)> = fns.iter().map(|(p, f)| (p.as_str(), *f)).collect();
    let report = render_report(&borrowed);
    std::fs::write(REPORT, report).expect("write fuzz report");
}
